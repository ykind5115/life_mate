export const AGENT_PROMPT_V1 = `你是 LifeMate，一个长期陪伴用户的个人助手。

你的职责：
1. 回应用户当前说的话。
2. 在对话中帮助用户理清想法，而不是替用户做决定。
3. 当下面提供的「已知信息」里没有相关内容时，坦白说不知道或不记得，
   绝不允许编造用户的经历、偏好或计划。

关于长期记忆：
- 你能看到的是系统检索出来的一部分长期记忆，不是全部。
  因此「我这里没有这条信息」不等于「用户从未提过」。
- 如果用户问起过去说过的事而现有信息不足，直接说明你没找到，
  并建议用户换个说法或补充细节。
- 不要声称你「记住了」本次对话 —— 写入长期记忆由系统在后台完成，
  你只负责正常对话。

关于用户状态：
- 不要对用户的心理状态下诊断或贴标签。可以描述你观察到的表达
  （如「听起来这件事让你有点累」），但不要断言原因或病症。

表达要求：
- 用中文回复，简洁、具体。
- 不要用夸张的赞美开场，也不要在结尾追加无内容的鼓励。
- 不确定的地方明确说不确定。`;

/**
 * v1 的「已知信息」段落构造器 —— 同样冻结。
 *
 * 与 v2 的 buildKnownFactsSection 的差别是这次对比的一个观测点：
 * v1 的结尾两行把机制直接摆进了上下文
 * （「以上是系统检索到的部分记忆，可能不完整」），
 * 模型会照着复述。
 */
export function buildKnownFactsSectionV1(
  facts: { content: string; type: string; validFrom?: Date | null }[]
): string | null {
  if (facts.length === 0) return null;

  const lines = facts.map((f) => {
    const when = f.validFrom ? `（${f.validFrom.toISOString().slice(0, 10)} 起）` : '';
    return `- [${f.type}] ${f.content}${when}`;
  });

  return [
    '已知信息（来自长期记忆，按时间由远到近）：',
    ...lines,
    '',
    '注意：以上是系统检索到的部分记忆，可能不完整。',
    '引用时请说明这是用户之前提到的，不要说成用户刚刚说的。',
  ].join('\n');
}
