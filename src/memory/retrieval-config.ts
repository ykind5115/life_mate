/**
 * ✅ RRF 平滑常量 k = 60（§18.4 明确给定）。
 *
 * k 越大，排名差异被压得越平。60 是 RRF 原始论文的推荐值，
 * 效果是「第 1 名与第 2 名的得分差距」远小于「第 1 名与第 50 名」。
 */
export const RRF_K = 60;

/** ✅ 各通道独立取 Top-50（§18.2） */
export const CHANNEL_LIMIT = 50;

/** ✅ 融合后取 Top-30 进入重排（§18.4） */
export const FUSION_LIMIT = 30;

/** ✅ 最终注入 Top-8（§18.5） */
export const INJECT_LIMIT = 8;

// ============================================================
// 重排权重（§18.4 阶段二）
// ============================================================

/**
 * ✅ 四项权重，和为 1.0（§18.4 明确给定）。
 *
 * final = 0.55 × norm(vector_score)
 *       + 0.20 × importance_score
 *       + 0.15 × type_aware_recency
 *       + 0.10 × source_count_signal
 */
export const RERANK_WEIGHTS = {
  vector: 0.55,
  importance: 0.2,
  recency: 0.15,
  sourceCount: 0.1,
} as const;

/**
 * ⚠️ 向量相似度的归一化下界（文档未给）。
 *
 * 为什么需要：余弦相似度理论范围 [-1, 1]，但真实短文本向量的
 * 无关内容相似度通常在 0.3~0.6 之间，负值几乎不出现。
 * 若按 [-1, 1] 归一化，一个 0.5 的「无关」结果会得到 0.75 的高分，
 * 把权重最多的那一项变成噪音。
 *
 * 取 0.5 作为「完全不相关」的基准：低于它的向量分归零，
 * 高于它的线性映射到 [0, 1]。
 *
 * 缺少向量的候选（向量生成失败、或只被关键词通道召回且回填失败）
 * 使用 NORM_VECTOR_MIN，即向量项得 0 —— 与「完全不相关」同等对待。
 */
export const NORM_VECTOR_MIN = 0.5;

/** 向量相似度归一化上界。1.0 是余弦相似度的理论上界 */
export const NORM_VECTOR_MAX = 1.0;

// ============================================================
// 时效衰减（§18.4 的 type_aware_recency）
// ============================================================

/**
 * ⚠️ 衰减半衰期（天）。文档只给了 state 的 14 天，其余由本实现补齐。
 *
 * decay(t) = 0.5 ^ (t / halfLife)
 *
 * 这里涉及两个未定值：
 *   · preference 的半衰期 —— §18.4 只说 `0.5 + 0.5 × decay(t)`，未给 t 的定义
 *   · event 参与排序时用哪个时间 —— §18.4 说「不降权，按时间排序即可」，
 *     但那个「时间」是 created_at（记录时间）还是 valid_from（事件时间）没写
 *
 * 本实现的取舍：
 *   preference 用 180 天。偏好是缓慢变化的，半年衰减一半是合理起点。
 *   event 的时间取 COALESCE(valid_from, created_at)：
 *     「去年三月换了工作」这件事的时效性由**事件发生时间**决定，
 *     而不是「用户什么时候告诉我们的」。用 created_at 会让
 *     用户刚补记的一年前的事看起来像新事。
 *
 * ⚠️ 这两个值必须由离线评测校准（PRD §15 的 Memory Recall 指标）。
 */
export const DECAY_HALF_LIFE_DAYS = {
  preference: 180,
} as const;

/**
 * source_count 信号的饱和点。
 *
 * sourceCount = 「这个事实被提到过几次」。重复提及是相关性信号，
 * 但边际收益递减：被提 3 次与 30 次不该有 10 倍差距。
 * 因此用 min(count, SATURATION) / SATURATION 压缩到 [0, 1]。
 */
export const SOURCE_COUNT_SATURATION = 5;
