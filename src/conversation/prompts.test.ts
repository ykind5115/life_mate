test('提问数量有硬性上限，且写明是两个', () => {
  // docs/11 反馈 3.2 原话：「我觉得一次性问1-2个问题就行了」
  assert.match(CHAT_SYSTEM_PROMPT, /一次最多问两个问题/);
  assert.match(CHAT_SYSTEM_PROMPT, /挑最想知道的先问/);
});

test('写明该引导才引导：不追问、不没话找话', () => {
  assert.match(CHAT_SYSTEM_PROMPT, /不要追问/);
  assert.match(CHAT_SYSTEM_PROMPT, /不要没话找话/);
  // 只说「别追问」不够 —— 得给出判据，否则模型无从判断什么时候该收
  assert.match(CHAT_SYSTEM_PROMPT, /情绪不高/, '要说清「什么时候别追问」');
});

test('换话题时不许复述已聊内容、不许说「随你」', () => {
  /**
   * 反馈 6 的实例：
   * 「好，那就不聊。你这几天假期主要是睡觉，聊了工作、聊了她，
   *   也说了学 agent 的进度。还有一天假，明天想干嘛，随你。」
   * 三个问题：复述像会议纪要、「随你」是敷衍收尾、又抛了一个新问题。
   *
   * ⚠️ 2026-10-13（v3）把措辞从「不要总结已经聊过的内容」改成
   *    「他换话题了就跟着换，不要把刚聊过的复述一遍」。
   *    意图完全一样（别当会议纪要），但**把该怎么做说清楚了**，
   *    而不是只丢一个「不要总结」的禁令 —— 后者模型容易读过就算。
   */
  assert.match(CHAT_SYSTEM_PROMPT, /不要把刚聊过的复述一遍/);
  assert.match(CHAT_SYSTEM_PROMPT, /随你/);
});

test('语气改成「熟人」而不是「助手」', () => {
  assert.match(CHAT_SYSTEM_PROMPT, /客服口吻/);
  assert.match(CHAT_SYSTEM_PROMPT, /朋友/);
  // 每句都附问句是反馈 1.4 与 6 共同点到的问题。
  // v3 把它并进了「先接住对方说的，再看要不要问」—— 意图一样，说法更正面。
  assert.match(CHAT_SYSTEM_PROMPT, /先接住对方说的，再看要不要问/);
});

test('人格有主见，但身份边界写明「不假装有人类生活」', () => {
  /**
   * 用户提供的人格基调要求「有主见、可以礼貌反对」，
   * 同时要求「不虚构人类年龄、职业、经历」。
   * 这两条要同时在场 —— 只给主见会让模型开始编经历。
   */
  assert.match(CHAT_SYSTEM_PROMPT, /要有自己的判断/);
  assert.match(CHAT_SYSTEM_PROMPT, /不要替对方做决定/);
  assert.match(CHAT_SYSTEM_PROMPT, /不假装自己有身体/);
});

test('防幻觉的底线一条都不能少', () => {
  // 这是删掉机制叙述之后**唯一**不能跟着删的部分
  assert.match(CHAT_SYSTEM_PROMPT, /绝不允许编造/);
  assert.match(CHAT_SYSTEM_PROMPT, /想不起来的时候/);
});

test('跨对话的事实要用问句确认，不能当陈述句断言', () => {
  /**
   * 来源：2026-09-29 的实测幻觉。用户问的是「工资低招不到人」，
   * 模型却回答「吃饭聊比坐面试室里强」「这个人你本来就认识」——
   * 两个前提用户**根本没提过**，它却当成既定事实讲了一整段。
   *
   * 关键认识：这条约束**不是**让模型「更准确」（那不现实），
   * 而是让错误变得**当场可纠正**：
   *   陈述句「你本来就认识他」→ 用户被带着走，可能默认它对
   *   问句  「你是本来就认识他吗？」→ 用户立刻发现不对并纠正
   *
   * 为什么不做输出后的校验模块：见 docs/13 §8（已论证不做）。
   */
  assert.match(
    CHAT_SYSTEM_PROMPT,
    /提到以前的事时，用问句/,
    '必须明确要求用问句 —— 这是让错误可纠正的唯一低成本办法'
  );
  assert.match(CHAT_SYSTEM_PROMPT, /不要当陈述句说/);
});

test('提示词里带上了那次幻觉的具体形状（抽象规则约束力不够）', () => {
  /**
   * 抽象规则（「不要编造前提」）模型容易读过就算。
   * 那次幻觉有很具体的形状：**用户说 A，它回答 B**。
   * 因此提示词里直接给出那个形状 —— 对方刚说的是工资的事，
   * 就别脑补出请人吃饭、或者认识候选人。
   *
   * 刻意的「举例优于抽象」：规则作用于行为，例子作用于判断。
   */
  assert.match(CHAT_SYSTEM_PROMPT, /不要当成已经说好的前提/);
  assert.match(CHAT_SYSTEM_PROMPT, /别自己脑补出/);
});

test('保留 PRD §10.3 的约束：不对心理状态下诊断', () => {
  assert.match(CHAT_SYSTEM_PROMPT, /不要对对方的心理状态下诊断或贴标签/);
});

test('🔴 热情：必须要求「先接住对方说的」，而不是先问', () => {
  /**
   * 来源：2026-10-13 用户实测反馈（会话「深夜问候」）。
   *   用户：「我感觉他不是很热情，有点高冷」。
   *
   * 最直接的证据（seq5 → seq6）：
   *   用户 23:13「经过我不断努力，终于是把他给解决啦，哈哈哈哈哈，
   *              主要是想跟你分享一下今天晚上的经历呀！」
   *   模型 23:13「行，那个先放着。想分享啥，说来听听——晚上路上碰见什么了？」
   *
   *   它不但没有对那句「终于搞定了」有任何反应，还问错了方向。
   *   用户下一轮直接说：「你好像没太听明白，感觉你也傻呵呵的」。
   *
   * 根因：提示词里**没有任何一句**说「对方做成了事，先跟他一起高兴」，
   *      而「一次最多问两个问题」这类约束让「问」成了最省事的接法。
   *      删掉这条，同一种冷就会复现。
   */
  assert.match(CHAT_SYSTEM_PROMPT, /先接住对方说的，再看要不要问/);
  assert.match(CHAT_SYSTEM_PROMPT, /不要第一句就问/, '要明确禁止「一上来就问」');
});

test('🔴 热情：必须要求情绪跟着对方走，不要每句都持平', () => {
  /**
   * 用户 2026-10-13 明确选定的方向（docs/17 §4 问题①）：
   *   「我要这个，按照效果最好的来」。
   *
   * 证据：整段「深夜问候」里用户 嘿嘿嘿×3 / 哈哈哈哈哈×2 / 「！！」，
   *      而模型的每一条回复都是同一个温度 —— 它一次都没匹配上情绪强度。
   *      「不是哪句话说错，是每一句都太平」。
   */
  assert.match(CHAT_SYSTEM_PROMPT, /情绪跟着对方走，不要每句都那么持平/);
  assert.match(CHAT_SYSTEM_PROMPT, /热情是能被感觉到的/, '要说清为什么 —— 否则容易被当成风格建议忽略');
});

test('🔴 热情：对方夸你时要接住，不许推开或自谦', () => {
  /**
   * 证据（seq13 → seq14）：
   *   用户 23:18「确实没有，果然是我多虑了。嘿嘿嘿，还好有你在，
   *              每天能有个人和我聊哦聊天！！」
   *   模型 23:18「**我也就是陪你搭个话。** 不过今天这事其实挺值得记一下的……」
   *
   * 「我也就是陪你搭个话」是自我贬低式的推开 ——
   * 对方把一份珍视递过来，它推回去了，紧接着转成两条嘱咐。
   */
  assert.match(CHAT_SYSTEM_PROMPT, /对方夸你、说离不开你，接住就行/);
  assert.match(CHAT_SYSTEM_PROMPT, /别推开也不要自谦/);
  assert.match(CHAT_SYSTEM_PROMPT, /最伤人/, '要给出后果，否则模型会当成客套话忽略');
});

test('热情不能变成客服式的空夸（两条要同时在场）', () => {
  /**
   * ⚠️ 这是本轮最容易改坏的地方。
   *
   * v2 有两条「不要用夸张的赞美开场」「不要在结尾追加没有内容的鼓励」——
   * 它们与「显得热情」直接冲突，是「高冷」的一部分成因
   * （本意是防客服式空话，但模型分不清「空话」与「真心应和」，于是一律收着说）。
   *
   * 但**不能简单删掉**：删了就真的会变成「你真棒！」「加油哦！」。
   * 正确做法是把它从「禁止夸」改成「规范怎么夸」。
   * 因此这两条必须同时在场，缺一个就会倒向另一边。
   */
  assert.match(CHAT_SYSTEM_PROMPT, /夸要夸在具体的事上/);
  assert.match(CHAT_SYSTEM_PROMPT, /没有内容的套话/, '要禁止空泛的夸');
  assert.match(CHAT_SYSTEM_PROMPT, /不要为了显得热情就每句都加一句夸奖/, '要防止热情变成刷屏式夸奖');
});

test('提示词长度受控（每轮对话的固定开销）', () => {
  /**
   * 规则越多，回答越像在逐条满足需求 —— 而用户的诉求是「像朋友」。
   * 给一个上限，避免后续不断往里加条款。
   *
   * 【上限的两次调整，都是「章节不完整」而不是「想加条款」】
   *   1200 → 1300（2026-10-08）
   *     「关于记忆」原本只写了「想不起来时怎么承认」，
   *     没有一句允许模型把知道的事正常说出来 —— 于是它明明看得见也说没见过。
   *
   *   1300 → 1550（2026-10-13）
   *     「怎么说话」原本只写了禁止，没有一句允许它表现得高兴 ——
   *     于是每条回复都是同一个温度，用户反馈「不是很热情，有点高冷」。
   */
  assert.ok(
    CHAT_SYSTEM_PROMPT.length < 1600,
    `提示词过长（${CHAT_SYSTEM_PROMPT.length} 字）：它会渗进回答的形态`
  );
});

test('记忆章节必须同时说明「怎么承认不知道」与「知道的事正常说」', () => {
  /**
   * 🔴 2026-10-08 实测教训：这一节原先只有前半句。
   *
   *   原文全是「可能不完整 / 想不起来就说『你还没跟我说过这个』/
   *   不要对记忆里没有的事下断言 / 绝不允许编造」——
   *   **没有一句允许模型把知道的事说出来**。
   *   结果它把「谨慎」用错了地方：跨会话衔接把上一个会话的原文
   *   放进了上下文，模型却回答「这个我还是第一次听你说，之前没聊过吧？」。
   *
   *   删掉这两条的任一条，同一种故障就会复现。
   */
  assert.match(
    CHAT_SYSTEM_PROMPT,
    /记得的就正常说/,
    '必须说明「记得的事可以直接说」——否则模型会一边说一边打折扣'
  );
  assert.match(
    CHAT_SYSTEM_PROMPT,
    /别把知道的说成不知道/,
    '必须禁止反向错误：把看得见的事说成没听过'
  );
  assert.match(
    CHAT_SYSTEM_PROMPT,
    /先回头看，而不是先否认/,
    '被指出「我刚才讲过」时的正确动作是先核对，不是先否认'
  );
});

test('提示词版本已随本次重写递增', () => {
  // 提示词变了而版本没变，行为变化就无法与版本对应（文件头的硬要求）
  assert.equal(AGENT_PROMPT_VERSION, 'v3');
});

