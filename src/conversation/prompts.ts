export interface KnownFactInput {
  /** 记忆正文（已由系统整理成人可读的一句话） */
  content: string;
  type: string;
  /** 该事实从何时起有效 */
  validFrom?: Date | null;
}

/**
 * 组装「你记得的事」段落。
 *
 * 【为什么标题是「你记得的」而不是「已知信息（来自长期记忆）」】
 *   v1 的写法把机制的说明直接摆进上下文，模型于是照着复述：
 *   「以上是系统检索到的部分记忆，可能不完整」——
 *   用户反馈 1 的原话是「这些东西放在正常的对话中就不像是朋友之间的」。
 *   改成第一人称的「你记得的」，模型引用时自然会说
 *   「你之前提过」，而不是「根据系统检索的结果」。
 *
 * 【为什么仍然显式标注日期】
 *   标注日期能让模型正确表述为「你之前提到过」而不是「你刚才说」。
 *   这个作用与机制叙述无关，不能一起删掉。
 *
 * 【为什么仍然要写「可能不完整」】
 *   防幻觉的底线：不写它，模型会把「这里没有」当成「对方从未提过」，
 *   进而断言「你从来没说过这件事」—— 那是在编造一个否定的结论。
 *   但表述换成人话：「不要因此断言对方没说过」，
 *   而不是 v1 的「系统检索到的部分记忆」。
 *
 * 返回 null 表示没有记忆可注入 —— 调用方应**完全不插入该段**，
 * 而不是插入一个空的「你记得的事：（无）」。空段落会被模型当成
 * 「确实没有」，而实际上可能只是本次没有触发检索。
 */
export function buildKnownFactsSection(facts: KnownFactInput[]): string | null {
  if (facts.length === 0) return null;

  const lines = facts.map((f) => {
    const when = f.validFrom ? `（${formatDate(f.validFrom)} 起）` : '';
    return `- [${f.type}] ${f.content}${when}`;
  });

  return [
    '你记得的关于对方的事（按时间由远到近）：',
    ...lines,
    '',
    '这些是你记得的部分，不是全部 —— 不要因为这里没有就断言对方没说过。',
    '提到它们时说「你之前提过」，不要说成对方刚刚说的。',
  ].join('\n');
}

/** 格式化为 YYYY-MM-DD。不用 toLocaleDateString：它的输出依赖运行环境 locale */
function formatDate(d: Date): string {
  return d.toISOString().slice(0, 10);
}
